SCALES = {"gad7": GAD7, "phq9": PHQ9}


def interpret(scale: str, answers: list[int]):
    """Возвращает (score, level, crisis_flag)."""
    spec = SCALES[scale]
    score = sum(answers)
    level = "Неизвестно"
    for lo, hi, label in spec["levels"]:
        if lo <= score <= hi:
            level = label
            break
    crisis = False
    if spec["crisis_threshold"] is not None:
        crisis = score >= spec["crisis_threshold"]
    elif scale == "phq9" and len(answers) >= 9:
        crisis = answers[8] > 0  # 9-й вопрос про самоповреждение
    return score, level, crisis
